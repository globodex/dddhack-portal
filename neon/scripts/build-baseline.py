#!/usr/bin/env python3
"""Regenerate the reviewed empty Postgres baseline from historical SQLite DDL.

This script opens only an in-memory SQLite database. It never opens user data,
connects to Postgres, or applies migrations. Review generated SQL before use.
"""
import hashlib
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'neon' / 'migrations'
connection = sqlite3.connect(':memory:')
files = sorted((ROOT / 'db' / 'migrations').glob('*.sql'))
for path in files:
    connection.executescript(path.read_text())
catalog = [dict(zip(('type', 'name', 'table', 'sql'), row)) for row in connection.execute(
    "SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY type,name"
)]


def translate(source):
    source = source.replace('`', '"')
    source = re.sub(r'\bjson_valid\(', 'portal_json_valid(', source, flags=re.I)
    source = re.sub(r'\bjson_extract\(', 'portal_json_extract(', source, flags=re.I)
    source = re.sub(r'\bjulianday\(', 'portal_instant(', source, flags=re.I)
    source = re.sub(r'\bjson_array\(', 'portal_json_array(', source, flags=re.I)
    source = source.replace('OLD.published_version_id IS NOT NEW.published_version_id',
                            'OLD.published_version_id IS DISTINCT FROM NEW.published_version_id')
    source = source.replace('NEW.name COLLATE BINARY=OLD.name COLLATE BINARY',
                            'NEW.name::text COLLATE "C"=OLD.name::text COLLATE "C"')
    source = re.sub(r'\bwindow\b', '"window"', source)
    source = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', source, flags=re.I)
    return source


tables = {obj['name']: obj for obj in catalog if obj['type'] == 'table'}
ordered = []
while len(ordered) < len(tables):
    pending = [name for name in tables if name not in ordered]
    ready = [name for name in pending if all(
        dep in ordered or dep == name for dep in re.findall(
            r'REFERENCES\s+[`"]?(\w+)', tables[name]['sql'], re.I))]
    if not ready:
        raise ValueError('Cyclic references require explicit migration review: ' + str(pending))
    ordered.extend(ready)

header = '-- Empty/synthetic database only. Generated by neon/scripts/build-baseline.py.\n'
header += '-- Historical SQLite migrations stay unchanged; review this PostgreSQL baseline.\n'
statements = []
for name in ordered:
    source = translate(tables[name]['sql'])
    if name in ('users', 'teams', 'registrations', 'registration_absences'):
        col = 'name' if name == 'teams' else 'email'
        source = re.sub(rf'([\"]?{col}[\"]?)\s+TEXT\b', r'\1 CITEXT', source, flags=re.I)
        source = re.sub(r'\s+COLLATE NOCASE\b', '', source, flags=re.I)
    if name in ('credit_inventory', 'project_review_history', 'project_feedback_reviews'):
        end = source.rfind(')')
        source = source[:end] + ', rowid INTEGER GENERATED ALWAYS AS IDENTITY UNIQUE' + source[end:]
    statements.append(source + ';')
statements.append('INSERT INTO scoring_revision(id,version) VALUES(1,0);')
statements.extend(translate(obj['sql']) + ';' for obj in catalog if obj['type'] == 'index')
(OUT / '0001_portal.sql').write_text(header + '\n\n'.join(statements) + '\n')

triggers = []
for obj in catalog:
    if obj['type'] != 'trigger':
        continue
    match = re.fullmatch(r'CREATE TRIGGER (\w+) (BEFORE|AFTER) (INSERT|DELETE|UPDATE(?: OF [\w,]+)?) ON (\w+)\s*(?:WHEN (.*?))?\s*BEGIN\s*(.*?)\s*END', obj['sql'], re.S)
    if not match:
        raise ValueError('Unrecognized trigger: ' + obj['sql'])
    name, timing, event, table, condition, body = match.groups()
    body = translate(body)
    body = re.sub(r"SELECT CASE WHEN (.*?) THEN RAISE\(ABORT,'([^']+)'\) END;",
                  lambda m: f"IF {m[1]} THEN RAISE EXCEPTION '{m[2]}' USING ERRCODE = '23514'; END IF;", body, flags=re.S)
    body = re.sub(r"SELECT RAISE\(ABORT,'([^']+)'\);",
                  lambda m: f"RAISE EXCEPTION '{m[1]}' USING ERRCODE = '23514';", body)
    if condition:
        body = 'IF ' + translate(condition) + ' THEN\n' + body + '\nEND IF;'
    if 'RAISE(ABORT' in body or 'SELECT CASE WHEN' in body:
        raise ValueError('Incomplete trigger translation: ' + name)
    ret = 'OLD' if event == 'DELETE' else 'NEW'
    triggers.append(f'''CREATE FUNCTION portal_trigger_{name}() RETURNS trigger LANGUAGE plpgsql AS $portal$
BEGIN
 {body}
 RETURN {ret};
END;
$portal$;
CREATE TRIGGER {name} {timing} {event} ON {table}
 FOR EACH ROW EXECUTE FUNCTION portal_trigger_{name}();''')
(OUT / '0002_invariants.sql').write_text(header + '\n\n'.join(triggers) + '\n')
manifest = {
    'source': 'final in-memory SQLite catalog; no records copied',
    'sqlite_migrations': {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in files},
    'tables': ordered,
    'triggers': [obj['name'] for obj in catalog if obj['type'] == 'trigger'],
    'indexes': [obj['name'] for obj in catalog if obj['type'] == 'index'],
}
(OUT / 'baseline-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Generated {len(tables)} tables, {len(triggers)} triggers, {len(manifest["indexes"])} explicit indexes')
